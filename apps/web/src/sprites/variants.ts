const cache = new Map<string, SpriteDef>();

/** Sprite d'une variante (mêmes dimensions que l'éclat de base ; 2 frames). */
export function shardVariant(f: Family, v: Variant): SpriteDef {
  if (v === 'classic') return SHARDS[f];
  const key = `${f}:${v}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const [a, b] = SHARDS[f].frames as [string, string];
  let def: SpriteDef;
  switch (v) {
    case 'night':
      def = { frames: [layer(a, STARS_A, MOON), layer(b, STARS_B, MOON)], keys: { ...NIGHT, H: SWEETIE.sun }, outline: true, fps: 2 };
      break;
    case 'landmark':
      // la médaille se pose par-dessus ; l'éclat garde sa palette d'origine
      def = { frames: [layer(a, MEDAL_A), layer(b, MEDAL_B)], keys: { ...SHARDS[f].keys, A: SWEETIE.berry, B: SWEETIE.blue, G: SWEETIE.orange, Y: SWEETIE.sun, H: SWEETIE.white }, outline: true, fps: 2 };
      break;
    case 'overclocked':
      def = { frames: [layer(FLAME_A, a), layer(FLAME_B, b)], keys: { ...HOT, F: SWEETIE.orange }, outline: true, fps: 6 };
      break;
    case 'shiny':
      def = { frames: [layer(a, SPARKLE_A), layer(b, SPARKLE_B)], keys: GOLD, outline: true, fps: 4 };
      break;
  }
  cache.set(key, def);
  return def;
}

/** Silhouette (case inconnue du Codex) : toute la forme en ardoise, sans étincelles. */
export function shardSilhouette(f: Family): SpriteDef {
  const key = `${f}:sil`;
  const hit = cache.get(key);
  if (hit) return hit;
  const base = SHARDS[f].frames[0]!;
  const letters = new Set(base.replace(/[.\s*+~]/g, ''));
  const keys: Record<string, string> = {};
  for (const l of letters) keys[l] = SWEETIE.slate;
  const def: SpriteDef = { frames: [base.replace(/[*+~]/g, '.')], keys, outline: true };
  cache.set(key, def);
  return def;
}

